export function lbl(lang: Lang, v: string): string;
export function lbl(lang: Lang, v: string | undefined): string | undefined;
export function lbl(lang: Lang, v: string | undefined): string | undefined {
  if (lang === "fr" || v === undefined) return v;
  const hit = EN_LABELS[v];
  if (hit !== undefined) return hit;
  for (const [re, f] of EN_PATTERNS) { const m = v.match(re); if (m) return f(...m); }
  return v;
}
